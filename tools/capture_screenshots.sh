#!/bin/bash
# Re-creates every published screenshot, and the data of the website's demo, from a
# synthetic disk of invented applications. Nothing of this machine appears in them.
#
#   tools/capture_screenshots.sh [build directory]     (default: build/release)
#
# Needs a logged-in window server session and cwebp (brew install webp). Writes PNG
# files to docs/assets/ and WebP + PNG files to website/assets/.
set -euo pipefail
command -v cwebp >/dev/null || { echo "cwebp is missing: brew install webp" >&2; exit 1; }

cd "$(dirname "$0")/.."
build="${1:-build/release}"
app="$build/VortexClean.app/Contents/MacOS/VortexClean"
work="$(mktemp -d)"
disk="$work/disk"
cleanup() { chmod -R u+w "$work" && rm -r "$work"; }
trap cleanup EXIT

"$build/tests/vortex_make_demo_disk" "$disk" "$PWD/$build/tests/process_child" >/dev/null
mkdir -p docs/assets website/assets

capture() { # <output name> <application> [more arguments]
    local name="$1" application="$2"
    shift 2
    for appearance in light dark; do
        local file="$work/$name-$appearance.png"
        local summary
        summary="$("$app" --root "$disk" --launch-check --appearance "$appearance" --snapshot "$file" "$@" \
            "$disk/Applications/$application.app" -AppleLocale en_US -AppleLanguages "(en)")"
        grep -q "\"scanned\":\"$application\"" <<<"$summary" || { echo "unexpected: $summary" >&2; exit 1; }
        cp "$file" "docs/assets/$name-$appearance.png"
        # The website serves lossless WebP, with a half-size PNG as the fallback. Not the
        # AVIF that sips writes: it is a HEIF-style tile grid, which Firefox cannot decode.
        cwebp -quiet -lossless -m 6 "$file" -o "website/assets/$name-$appearance.webp"
        sips --resampleWidth 1180 "$file" --out "website/assets/$name-$appearance.png" >/dev/null
        echo "captured $name-$appearance"
    done
}

capture standard "PixelForge Studio"
capture package "Tidewater Backup"
capture suite "Fernwood Writer" --hover 2

# The data behind the website's interactive demo: what the engine itself reports for
# the same three applications, with the temporary directory taken out of the paths.
real="$(cd "$disk" && pwd -P)"
scan() { # <export name> <application>
    printf 'export const %s = ' "$1"
    "$app" --root "$disk" --scan "$disk/Applications/$2.app" |
        sed -e "s|$real/Users/demo|~|g" -e "s|$real||g" -e '/"scan_seconds"/d' -e '/"last_used_epoch"/d' -e 's/"notes": \[\],$/"notes": []/'
    printf ';\n'
}
{
    printf '// Generated by tools/capture_screenshots.sh from the output of VortexClean --scan\n'
    printf '// on a synthetic disk. Every application in it is invented. Do not edit by hand.\n'
    scan standard "PixelForge Studio"
    scan packaged "Tidewater Backup"
    scan suite "Fernwood Writer"
} >website/demo-data.js

# The icons of the three sample applications, for the demo's list.
for pair in "standard:PixelForge Studio" "packaged:Tidewater Backup" "suite:Fernwood Writer"; do
    sips -s format png --resampleWidth 128 "$disk/Applications/${pair#*:}.app/Contents/Resources/AppIcon.icns" \
        --out "website/assets/app-${pair%%:*}.png" >/dev/null
done

# The application icon, as the build renders it.
sips -s format png "$build/VortexClean.app/Contents/Resources/VortexClean.icns" --out "$work/icon.png" >/dev/null
sips --resampleWidth 512 "$work/icon.png" --out website/assets/icon-512.png >/dev/null
sips --resampleWidth 180 "$work/icon.png" --out website/assets/icon-180.png >/dev/null
sips --resampleWidth 64 "$work/icon.png" --out website/assets/favicon-64.png >/dev/null
cp website/assets/icon-512.png docs/assets/icon.png
